namespace PillsTracker.Domain

/// <summary>
/// Ошибки, возникающие при работе с доменными сущностями курса,
/// дозировок, расписаний и правил приёма.
/// Эти ошибки отражают нарушения бизнес-логики.
/// </summary>
type DomainError =
    /// <summary>
    /// Некорректная длительность курса.
    /// Например, длительность равна нулю или отрицательна.
    /// </summary>
    | InvalidDuration of string

    /// <summary>
    /// Некорректное время приёма дозы.
    /// Например, время находится вне допустимого диапазона.
    /// </summary>
    | InvalidDoseTime of string

    /// <summary>
    /// Приём препарата произошёл слишком рано относительно планового времени
    /// или относительно другого препарата (при взаимодействиях).
    /// </summary>
    | IntakeTooEarly of string

    /// <summary>
    /// Приём препарата произошёл слишком поздно относительно планового времени
    /// или нарушает правила взаимодействия.
    /// </summary>
    | IntakeTooLate of string

    /// <summary>
    /// Нарушено отношение приёма к еде (до еды, с едой, после еды).
    /// </summary>
    | MealRelationViolation of string

    /// <summary>
    /// Попытка изменить или продолжить курс, который уже завершён.
    /// </summary>
    | CourseAlreadyFinished

    /// <summary>
    /// Попытка повторно отметить приём дозы, которая уже была принята.
    /// </summary>
    | DoseAlreadyTaken


/// <summary>
/// Ошибки, возникающие при создании или проверке правил взаимодействия препаратов.
/// Эти ошибки отражают нарушения структуры или содержания InteractionRule.
/// </summary>
type InteractionError =
    /// <summary>
    /// Группа A не может быть пустой.
    /// Взаимодействие должно включать хотя бы один препарат в каждой группе.
    /// </summary>
    | EmptyGroupA

    /// <summary>
    /// Группа B не может быть пустой.
    /// Взаимодействие должно включать хотя бы один препарат в каждой группе.
    /// </summary>
    | EmptyGroupB

    /// <summary>
    /// Один и тот же препарат не может находиться одновременно в группах A и B.
    /// Это нарушает смысл разделения групп.
    /// </summary>
    | SamePreparationInBothGroups of PreparationId

    /// <summary>
    /// Описание взаимодействия не может быть пустым.
    /// Оно должно содержать понятное объяснение влияния.
    /// </summary>
    | InvalidDescription of string
