namespace PillsTracker.Domain

open System

/// <summary>
/// Доменные сервисы, связанные с курсами приёма препарата.
/// Содержат чистые операции, которые используют порты (интерфейсы)
/// для взаимодействия с внешними системами, не нарушая чистоту домена.
/// </summary>
module CourseService =

    /// <summary>
    /// Планирует отправку уведомления о приближении приёма препарата.
    /// Логика:
    /// 1. Вычисляет точное время напоминания на основе даты и времени дозы.
    /// 2. Учитывает параметр NotifyBeforeMinutes.
    /// 3. Если время напоминания уже наступило — отправляет уведомление.
    ///
    /// Важно:
    /// - Функция не создаёт таймеры и не планирует будущие события.
    /// - Она лишь определяет, нужно ли отправить уведомление прямо сейчас.
    /// - Реальная система напоминаний должна вызывать эту функцию периодически.
    /// </summary>
    /// <param name="notify">Порт уведомлений, реализуемый внешним адаптером.</param>
    /// <param name="dose">Доменная сущность приёма препарата.</param>
    /// <returns>
    /// Ничего не возвращает. Если время напоминания наступило — вызывает порт уведомлений.
    /// </returns>
    let scheduleReminder (notify: INotificationService) (dose: CourseDose) =
        let reminderTime =
            dose.PlannedDate
                .Add(dose.PlannedTime)
                .AddMinutes(float -dose.NotifyBeforeMinutes)

        if DateTime.UtcNow >= reminderTime then
            notify.SendReminder dose

